import { sqliteTable, text, integer } from "drizzle-orm/sqlite-core";
export const mailboxConnections = sqliteTable("MailboxConnection", {
  ownerId: text().primaryKey(),
  id: text().notNull(),
  address: text().notNull(),
  host: text().notNull(),
  passwordSeal: text().notNull(),
  createdAt: integer().notNull(),
  lastSyncAt: integer(),
  lastAttemptAt: integer(),
  uidValidity: text().notNull(),
  lastUid: integer().notNull(),
  syncLease: text(),
  syncLeaseAt: integer(),
  lastError: text(),
  version: integer().notNull(),
  folderState: text().notNull().default("{}"),
  folderLeaseAt: integer(),
});
export const mailboxRemoteMessages = sqliteTable("MailboxRemoteMessage", {
  id: text().primaryKey(),
  ownerId: text().notNull(),
  connectionId: text().notNull(),
  folder: text().notNull(),
  path: text().notNull(),
  uid: integer().notNull(),
  uidValidity: text().notNull(),
  sender: text().notNull(),
  recipient: text().notNull(),
  subject: text().notNull(),
  body: text().notNull(),
  receivedAt: integer().notNull(),
  isRead: integer().notNull(),
});
export const mailboxMessages = sqliteTable("MailboxMessage", {
  id: text().primaryKey(),
  connectionId: text().notNull(),
  ownerId: text().notNull(),
  uid: integer().notNull(),
  uidValidity: text().notNull(),
  sender: text().notNull(),
  recipient: text().notNull(),
  subject: text().notNull(),
  body: text().notNull(),
  receivedAt: integer().notNull(),
  isRead: integer().notNull(),
  candidate: integer().notNull(),
  truncated: integer().notNull(),
});
export const mailboxDrafts = sqliteTable("MailboxDraft", {
  id: text().primaryKey(),
  ownerId: text().notNull(),
  connectionId: text().notNull(),
  recipient: text().notNull(),
  subject: text().notNull(),
  body: text().notNull(),
  status: text().notNull(),
  version: integer().notNull(),
  updatedAt: integer().notNull(),
});
export const mailboxAttempts = sqliteTable("MailboxConnectAttempt", {
  ownerId: text().primaryKey(),
  startedAt: integer().notNull(),
  attempts: integer().notNull(),
});
